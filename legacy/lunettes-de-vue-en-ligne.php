<h2>Qui est Optical Center ?</h2>

<p>
L'enseigne Optical Center est une marque incontournable de lunettes de vue, de soleil et de lentilles de contact créée en 1991.<br>
La marque a connu un développement rapide lui permettant de proposer une gamme complète de lunettes au prix les plus bas.<br>
Optical Center a également commercialisé sa propre gamme de lunettes afin de réduire au maximum le coût à la charge du client.</p>
<p>
Optical Center dispose de plus de 500 magasins répartie dans l'ensemble régions françaises et dans plusieurs autres pays.<br>
Ce développement rapide de la marque s'explique notamment par les efforts de la marque au quotidien afin de répondre aux attentes des clients.<br>
Ces derniers recherchent des lunettes de vue de qualité, esthétique et au meilleur prix et Optical Center permet de répondre à ces exigences aussi bien en ligne qu'en magasin.<br>
</p>
<br>

<h2>La vente de lunettes de vue en ligne chez Optical Center</h2>

<p>
En 2006, Optical Center lance son site d'internet en ligne <u>http://www.optical-center.fr</u> afin de permettre à chaque internautes d'acquérir sa paire de lunettes de vue de grande marque au meilleur prix.<br>
L'ensemble des internautes ayant achetés des lunettes de vue sur le site de Optical Center s'accorde à dire que le site est intuitif et simple d'utilisation.<br>
Les lunettes de vue sont classées par catégorie et par marque facilitant ainsi la navigation et permettant de trouver rapidement la paire de lunettes souhaitées.</p>
<p>Concernant les moyens de paiement,  Optical Center a mit en place plusieurs manières de paiement afin de faciliter la transaction pour l'ensemble des internautes.<br>
Le petit cadenas présent sur chaque page du site permet aux internautes de s'assurer que le site est entièrement sécurisé au cours de chaque transaction.<br>
Sur son site internet, Optical Center a mit en place un support client sur lequel les internautes peuvent obtenir des conseils personnalisés de la part d'un opticien qualifié.
</p>
