<h2>Biographie de Laurent Levy</h2>

<p>
Né le 7 octobre 1966 à Neuilly-sur-Seine, le fondateur d'Optical Center Laurent Levy est diplômé en 1989 du brevet professionnel d’opticien lunettier dans le 15ième arrondissement de Paris.</br>
Laurent Levy ouvre la première boutique Optical Center en 1991 à Boulogne-Billancourt dont la surface était de 26 m2.</p>
<p>
Six ans après, Laurent Levy ouvre sa première franchise à Rouen qui marqua le début du  développement de la marque.</br>
C'est en l'an 2000 que Laurent Levy commence à créer ses propres marques de lunettes de vue ainsi que des lentilles de contact.</br>
Optical Center a commencé à lancer les marques Oscar Version et OuieZen puis d'autres au fil des années.</br>
Toutes les marques de lunettes créées par Optical Center sont vendues uniquement dans les magasins de la marque.</br>
Afin de partager son savoir et sa vision du management, Laurent Levy devient en 2003 professeur et membre du Jury dans la célèbre et prestigieuse école HEC entrepreneurs.</br>
</p>
</br>
<h2>Laurent Levy : Un PDG novateur</h2>

<p>
En 2006, Optical Center lance sa première boutique en ligne.</p>
Celle-ci propose une généreuse gamme de produits liés à l'optique et connaît rapidement un grand succès auprès des internautes.</br>
Installé à Jérusalem depuis 2005, Laurent Levy crée en 2007 la fondation Optical Center dans cette même ville.</br>
Cette fondation a pour objectif d'aider toutes les personnes à faibles revenus d'acquérir des lunettes de vue à un prix dérisoire.</br>
Soucieux de satisfaire au mieux les besoins de ses clients, Laurent Levy lance en 2008 un service d’audio-prothèse dans les boutiques Optical Center.</p>
<p>
En 2011, Laurent Levy prend la plume afin de rédiger son premier ouvrage intitulé «Les secrets de la réussite» expliquant comment réussir dans les univers professionnels très concurrentiels.</p>
<p>
L'année 2012 fut une année charnière dans le développement du digital d'Optical Center.</br>
La marque lance la première franchise d'optique sur internet et elle devient alors novatrice dans le domaine.</br>
Sur son site internet, Optical Center lance également un logiciel innovant d'essayage en ligne de lunettes.</br>
Passionné de musique, Laurent Levy crée à titre personnel le premier site de musique hébraïque surnommé Hebrew Musics en 2014.</p>
<p>
En 2015, Laurent Levy lance ses deux premiers magasins d'optique au centre ville de Jérusalem.</br>
Il ouvre notamment une boutique dans la célèbre et incontournable rue Ben Yeouda connue dans le monde entier.</p>
<p>
En 2016, Laurent Levy est une nouvelle fois innovateur en créant la première clinique de chirurgie réfractive dans la ville de Lyon.</br>
De jour en jour, Laurent Levy continue le développement de son enseigne à travers plusieurs pays et dispose désormais de plus de 500 magasins faisant d'elle la troisième enseigne d'optique en France.</br>
Au rythme du développement de la marque et des efforts de son fondateur et de ses 2800 collaborateurs, il ne serait pas étonnant de voir Optical Center prendre la première place du podium au cours des prochaines années.</p>

