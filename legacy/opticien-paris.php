<h2>La diversité d'opticiens à Paris</h2>

<p>
Le métier d'opticien séduit en France depuis des décennies si bien qu'il y aurait près de 30% d'opticiens en trop en métropole.<br>
Ce métier séduit les futurs diplômés en raison des perspectives d'évolution possibles ainsi que par passion du métier.</p>
<p>
Selon les statistiques, il y a environ 200 opticiens à Paris intra-muros répartis sur l'ensemble des arrondissements.<br>
Les personnes recherchant un opticien ont le choix entre des opticiens indépendants ou appartenant à de grandes chaînes de l'optique.<br>
Chaque opticien propose sa gamme de lunettes de vue, lunettes de soleil, lentilles de contact ainsi que divers accessoires liés à l'optique.<br>
Parmi ces différents opticiens, l'enseigne Optical Center a su s'imposer sur Paris en tant que leader de l'optique.</p>
