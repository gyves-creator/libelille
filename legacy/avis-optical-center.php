<h2>Avis Optical Center des clients en boutiques classiques</h2>
</br>
<p>
<u>Jérémy, client depuis 2 ans :</u>
</p>
<p>
J'habite dans un quartier où il y a plusieurs opticiens qui proposent à peu près les mêmes produits.</br>
Au départ, j'ai fait le choix d'Optical Center car je connaissais la marque notamment par la publicité à la télévision.</br>
Tout d'abord, j'aime la clarté du magasin dans lequel la couleur blanche s'associe à la brillance du mobilier.</br>
Le côté moderne du magasin Optical Center dans lequel j'achète rend agréable la visite.</br>
Les opticiens qui me reçoivent sont compétents et savent répondre entièrement à mes attentes.</br>
Les employés me proposent à chaque fois une boisson chaude ce qui rend l'achat sympathique.</br>
L'achat se passe donc très bien et c'est pour cela que cela fait maintenant environ 2 ans que je suis client de l'enseigne.</br>
</p>
<p>
<u>Sylvie, cliente depuis 4 ans :</u>
</p>
<p>
Je suis cliente chez Optical Center dans l'un des magasins situés en région parisienne.</br>
Ce que j'apprécie chez cet opticien c'est la proximité avec ses clients et la connaissance parfaite de leurs besoins.</br>
Lorsque je rentre dans le magasin, l'opticien ressort mon dossier dans lequel il y a l'historique de mes derniers achats et de mes besoins précis.</br>
Optical Center propose aussi bien des lunettes pour la vue que pour le soleil, ce qui permet d'acheter en même temps mes solaires dès que l'été approche.</br>
Le magasin vend aussi des produits disponibles uniquement dans leur magasin, ce qui me permet d'acquérir des lunettes originales.</br>
</p>
