<h2>Que pensent les clients Optical Center achetant sur le site internet ?</h2>
</br>
<p>Les ventes en ligne des lunettes de vue et de soleil sont de plus en plus fréquentes au fil des années.</br>
De ce fait, il nous a semblé judicieux de connaître les avis sur Optical Center émanant des acheteurs en ligne.</br>
</p>
<p>
<u>Patrick, acheteur en ligne depuis 1 an :</u>
</p>
<p>
Cela ne fait pas très longtemps que je commande mes lunettes chez Optical Center mais je suis réellement satisfait de mes premiers achats.</br>
Le fait que les opticiens dialoguent avec les clients en direct est vraiment une très bonne chose pour les clients.</br>
On ne se sent pas seul lors de notre achat, on se fait guider par un spécialiste de la même manière qu'en magasin.</br>
Je trouve super la technologie qu'ils ont inventé concernant l'essayage en ligne des lunettes de vue ou de soleil.</br>
Cela permet de savoir si une paire de lunettes est adaptée à notre visage de la même manière qu'en magasin.</br>
Je suis également utilisateur de l'application sur mon téléphone et celle-ci me rend parfois bien des services lorsque je suis en voyage.</br>
</p>
<p>
<u>Yann, acheteur depuis 2 ans :</u>
</p>
<p>
J'habite une petite ville où il n'y a pas d'opticien à proximité de mon domicile car ma maison est un peu excentrée.</br>
