<h2>La vente de lunettes de vue en ligne : un marché ultra-compétitif</h2>

<p>
La démocratisation d'internet a littéralement changé le mode de consommation des Français.<br>
Selon un récent sondage, plus de 65% des ménages français disposent d'une connexion internet dans leur domicile.<br>
L'arrivée des smartphones a largement facilité l'utilisation d'internet et toutes les classes sociales sont concernées par cette révolution.</p>
<p>
Comme l'ensemble des secteurs d'activité, l'optique a connu une révolution avec le développement de nombreux sites d'optique en ligne.<br>
La plupart des grandes marques de l'optique ont su anticiper l'essor du marché de l'optique en ligne.<br>
Ces marques ont alors lancé leur site internet afin de proposer leur gamme de lunettes de vue, lunettes de soleil et lentilles de contact.</p>
<p>
Certaines marques de l'optique, déjà bien implantées en France, n'ont pas cru à la vente de lunettes en ligne et ont pris un certain retard sur leurs concurrents avant de s'investir pleinement sur ce canal de vente.<br>
Hormis le développement des sites e-commerce des leaders de l'optique, de nouveaux acteurs sont apparus.<br>
Ces derniers exercent leur activité uniquement sur internet sans disposer de points de vente classiques.<br>
Ce nombre important d'opticiens en ligne a saturé le marché et il est difficile pour les opticiens de se démarquer de la concurrence.</p>
<br>


<h2>Optical Center : un leader de l'optique en ligne</h2>

<p>
L'enseigne Optical Center a su rapidement s'imposer comme étant un opticien incontournable avec son réseau de plus de 600 magasins.<br>
Présente en France et dans de nombreux autres pays, la marque a prouvé qu'il était possible d'allier qualité et prix bas.<br>
C'est en 2006 qu'Optical Center lance son propre site e-commerce de vente en ligne et permet aux internautes d’accéder à son catalogue complet de lunettes de vue, lunettes de soleil et lentilles de contact.</p>
<p>
La gestion du site en ligne a été effectuée de la même manière que pour les points de vente en mettant au centre des processus le client.<br>
Un service qualité a été mis en place afin de connaître les attentes des clients et les points d'amélioration.<br>
C'est ainsi que le site de la marque Optical Center a connu un succès rapide et est devenu la référence de la vente de lunettes de vue, lunettes de soleil et de lentilles de contact.</p>
<br>

<h2>Les atouts de la vente en ligne chez Optical Center</h2>

<p>
Le succès du site internet d'Optical Center s'explique par de nombreuses raisons évoquées par différents clients de la marque.<br>
La qualité des lunettes et le prix semblent être les deux principales raisons expliquant la place de leader d'Optical Center.<br>
En effet, l'enseigne propose en ligne toutes les plus grandes marques de lunettes aux meilleurs prix sur le marché.<br>
Les clients de la marque interrogés s'accordent à dire que le choix de lunettes de vue est très vaste, ce qui permet à chacun de trouver la paire qu'il souhaite.<br>
Un autre point concerne la facilité de navigation sur le site internet jusqu'au paiement de la paire de lunettes.</p>
<p>
Les lunettes de vue et de soleil sont classées par marque avec la possibilité d'appliquer différents filtres afin de trouver la paire répondant entièrement à ses besoins.<br>
En outre, Optical Center a mis en place un système de discussion en direct avec un opticien chargé d'aiguiller le client dans son choix et de l'aider jusqu'au processus d'achat.<br>
Les clients d'Optical Center interrogés ont également indiqué apprécier les nombreux bons de réduction envoyés par la marque afin de les remercier de leur fidélité.<br>
Le succès de l'enseigne Optical Center n'est pas dû au hasard et résulte des efforts de la direction dont l'objectif est de satisfaire l'ensemble de ses clients.</p>
