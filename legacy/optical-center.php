<h2>Un peu d'histoire sur Optical Center</h2>

<p>
La première boutique d'Optical Center a été lancée au cours de l'année 1991 en région parisienne par son fondateur Laurent Levy.</br>
Rapidement, les produits de la marque ont du succès, ce qui a permis à son fondateur de lancer sa première franchise six ans plus tard dans la ville de Rouen.</br>
C'est dans les années 2000 qu'Optical Center lance ses propres produits d'optique tels que les lentilles de contact ou les lunettes.</br>
Ces produits sont commercialisés uniquement dans les magasins de la marque.</br>
Suite au développement rapide d'internet, Optical Center lance son premier site de vente en ligne.</br>
Les franchises Optical Center se succèdent par dizaines et comptent aujourd'hui plus de 570 boutiques.</br>
C'est en 2016 qu'Optical Center, sous le direction de son fondateur, lance à Lyon une clinique de chirurgie d'optique.</br>
Cette dernière était inédite en France et permet à la marque de se démarquer d'avantage de ses concurrents.</br>
</p>
</br>
<h2>Les lunettes de vue et lentilles de contact vendues par Optical Center</h2>

<p>
Les français portent de plus en plus de lunettes de vue quelque soit leur âge et la région dans laquelle ils vivent.</br>
L’œil humain est plutôt fragile et de fait il peut être affecté par différents troubles à n'importe quel âge.</br>
Bien entendu, plus une personne prend de l'âge, plus ses yeux sont fragilisés et plus son besoin de porter des lunettes sera grand.</br>
Cependant, il devient de plus en plus fréquent de voir des enfants de 4 ans porter des lunettes de vue à cause d'un soucis dès leur naissance.</br>
Avec l'avancée des études sur l'optique, les problèmes de vue sont rarement graves.</br>
Les ophtalmologues combinés au savoir-faire des opticiens tels qu'Optical Center sont capables de corriger les problèmes de vue.</br>
Pour cela, le patient doit tout d'abord se rendre chez l'ophtalmologue avant de s'adresser à un opticien tel que Optical Center qui saura le guider efficacement.</p>
<p>
Chaque personne ayant des problèmes de vue et s'adressant à une boutique Optical Center aura le droit à un traitement personnalisé.</br>
Toutes les boutiques Optical Center gardent scrupuleusement tous les dossiers de leurs clients afin de connaître exactement le besoin de chacun.</br>
Concernant la vente en magasin des lunettes de vue Optical Center, il faut savoir qu'il existe des milliers de référence.</br>
Les grandes marques de l'optique se retrouvent dans les étalages de tous les magasins Optical Center.</br>
Optical Center vend à titre d'exemple des lunettes de vue Prada, Vuarnet, Dior...</br>  
La marque commercialise également ses propres lunettes de vue afin de proposer le meilleur de l'optique à petit prix.</br> 
Concernant les lentilles de contact,  Optical Center vend également les meilleurs produits dans ce domaine.</br>
En outre, Optical Center propose également des lunettes de vue spécialement pour les enfants ainsi que des montures originales pour les adultes souhaitant se faire remarquer.</br>
</p>
</br>
<h2>Les lunettes de soleil vendues par Optical Center</h2>

<p>
Les opticiens ne se contentent pas de proposer uniquement des lunettes de vue visant à corriger la vision des personnes.</br>
Ce métier commercialise également les lunettes de soleil visant à se protéger du rayonnement solaire pouvant être dangereux pour les yeux.</br>
En été, nos yeux doivent constamment faire face au soleil qui peut altérer la vue de chaque personne.</br>
En se protégeant bien du soleil par le biais de lunettes de soleil efficaces, cela permet d'éviter tout problème lié à ce rayonnement.</br>
Il faut savoir également que les lunettes de soleil sont également indispensables au ski en hiver.</br>
Il est donc très important de protéger ses yeux aussi bien en été qu'en hiver.</br>
A ce titre, Optical Center distribue dans ses points de vente une gamme complète de lunettes de soleil pour tous les goûts et de tous les styles.</br>
Afin de protéger au mieux ses clients, Optical Center propose plusieurs types de verres en fonction du besoin de chacun.</p>
<p>Il propose aussi plusieurs coloris afin d'offrir plus de choix à ses clients en magasin ou sur internet.</br> 
Il a été prouvé que le budget des français pour l'achat des lunettes de vue a augmenté, ce qui prouve que cet accessoire de mode est devenu indispensable.</br>
Afin de répondre au mieux à cette demande, Optical Center offre quotidiennement à sa clientèle les marques les plus recherchées et les plus connues.</br>
Les grandes marques de lunettes de vue telles que Rayban, Prada,Vuitton sont présentées dans tous les magasins de la marque.</br>
La société Optical Center s'efforce de constamment tirer le prix des produits vers le bas afin que chacun puisse se faire plaisir sans trop dépenser.</br>
</p>
 
