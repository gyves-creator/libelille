<h2>Les franchises d'Optical Center</h2>

<p>
Depuis que la société Optical Center s'est lancée dans la franchise, elle n'a cessé de multiplier les ouvertures de magasins.</br>
Cependant, pour devenir franchisé Optical Center, il est impératif de travailler déjà pour la marque.</br>
En effet, cette dernière ne permet pas à un opticien externe d'ouvrir une franchise.</br>
Cette stratégie propre à Optical Center a été décidée par la direction depuis le début de l'activité.</br>
Cependant, il se peut que la marque modifie cette règle dans les prochaines années en fonction du développement de la marque.</br>
Malgré cette restriction au niveau des franchises, Optical Center compte tout de même des centaines de franchisés.</br>
</p>
