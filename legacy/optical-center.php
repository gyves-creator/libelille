<h2>Le site internet d'Optical Center : une boutique en ligne intuitive</h2>

<p>
Les nouvelles technologies ont su s'intégrer très rapidement auprès des ménages français.</br>
En parallèle, le e-commerce a pris beaucoup d'ampleur ces dernières années au détriment des magasins classiques.</br>
Plus de 70% des français disposent d'un ordinateur et se connectent à internet régulièrement.</br>
Afin de répondre aux attentes des internautes souhaitant acheter leurs lunettes de vue ou de soleil sur internet, Optical Center a développé sa propre boutique de vente en ligne.</br>
Celle-ci est accessible aussi bien sur ordinateur que sur tablette ou mobile.</br>
Le site internet d'Optical Center est divisé en catégories afin de rendre facile la recherche de produits.</br>
A titre d'exemple, prenons le cas d'une personne qui recherche une paire de soleil Rayban en ligne sur le site Optical Center.</br> 
Il suffit de cliquer sur la rubrique de lunettes de soleil et de cocher la marque Rayban afin que tous les produits de cette marque apparaissent directement sur l'écran.</br>
Il en est de même pour la recherche d'une paire de lunettes de vue ou de soleil sur le site internet d'Optical Center.</br>
</p>
