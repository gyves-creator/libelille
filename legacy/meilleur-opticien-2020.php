<h2>Le marché de l'optique en France</h2>

<p>
Le nombre d'opticiens en France n'a cessé d'augmenter au cours des années et il y aurait à cet effet « trop d'opticiens», rendant le marché saturé.<br>
Avec le développement d'internet, de nombreux nouveaux acteurs sont arrivés sur le marché de l'optique en proposant leurs produits sur leur site en ligne.</p>
<p>
Au fil du temps, l'achat de lunettes sur internet s'est démocratisé et de très nombreux internautes achètent désormais leur paire de lunettes auprès d'opticiens sur la toile.<br>
Or, face à ce nombre important d'offreurs sur le marché de l'optique, il n'est pas toujours facile de faire son choix.<br>
Comparer les opticiens entre eux est une démarche chronophage et plutôt difficile.<br>
Afin de vous aider à choisir votre opticien pour 2020, nous avons comparé les différentes enseignes pour vous aider à faire un choix.</p>
<br>

<h2>Les critères retenus pour notre choix</h2>

<p>
Afin de déterminer notre meilleur opticien pour 2020, nous avons notamment retenu 3 critères qui nous semblent indispensables pour notre choix.<br>
</p>

<h3>Les gammes de lunettes et les prix</h3>

<p>
Pour qu'un client soit satisfait de son opticien, celui-ci doit être en mesure de lui proposer une gamme complète de lunettes répondant à ses attentes et au meilleur prix du marché.<br>
Chaque porteur de lunettes dispose de critères personnels et l'opticien doit être en mesure de répondre à toutes ses attentes.</p>
<br>

<h3>La qualité des lunettes de vue</h3>

<p>
Les lunettes de vue sont utilisées en continu et il est impératif que l'opticien propose à ses clients des produits de qualité irréprochable.<br>
Pour cela, la durabilité dans le temps des lunettes est un critère déterminant pour les acheteurs.</p>
<br>

<h3>Les délais</h3>

<p>
Un opticien doit impérativement respecter les délais indiqués à ses clients concernant la mise à disposition des lunettes commandées.<br>
L'opticien a l'obligation de fournir les lunettes commandées à la date fixée au préalable et sans retard.</p>
<br>

<h2>Notre choix pour 2020 : Optical Center</h2>

<p>
Suite à notre étude, nous avons élu comme meilleur opticien pour 2020 l'enseigne Optical Center.<br>
Lancé en 1991, Optical Center a su s'imposer en tant que leader dans le marché de l'optique aussi bien en point de vente que sur internet.</p>
<p>
Le succès d'Optical Center s'explique notamment par le fait que cette enseigne ait su comprendre les attentes de ses clients en leur proposant un service de qualité irréprochable et des produits aux meilleurs tarifs du marché.<br>
Afin de poursuivre son développement, Optical Center a lancé une campagne de recrutement de 400 opticiens et 300 audioprothésistes dans toute la France.</p>
