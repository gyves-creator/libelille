<h2><span style="color: #000000;">L'équipe de France réitère son exploit 20 ans après</span></h2>

<p>
C'est au stade Loujniki à Moscou que l'équipe de France a levé pour la seconde fois la coupe du monde de football tant convoitée par l'ensemble des pays.<br>
Tous les spécialistes s'accordent à dire que le match était loin d'être gagné, notamment après le premier quart d'heure de la rencontre.<br>
Les Croates monopolisent le ballon, rendant le match étouffant pour l'ensemble des supporters de l'équipe de France.</p>
<p>
Un but contre son camp de Mandzukic à la 18ième minute permet à notre équipe nationale de se décrisper et surtout de prendre une première longueur d'avance sur la Croatie.<br>
L'égalisation de Perišic 10 minutes plus tard confirme la qualité de jeu de l'équipe croate.<br>
Puis vinrent les 3 buts de la libération signés Griezmann, Pogba et Mbappé, anéantissant tous les espoirs des croates malgré une réduction du score de 4 à 2 à la suite d'une erreur de Lloris à la 69ième minute.</p>
<p>
Plusieurs milliers de supporters français ont assisté à cette finale épique et plus d’un milliard de personnes ont assisté devant leur écran à la victoire des bleus.<br>
Parmi les Français ayant fait le déplacement en Russie, la célèbre enseigne d'optique Optical Center
était présente lors de cette finale.</p>
<br>

<h2>Optical Center apporte un fervent soutien aux bleus lors de la finale de la coupe du monde</h2>

<p>
Avec plus de 500 magasins dans le monde, Optical Center est un leader incontesté de l'optique.<br>
La marque a d’ailleurs été élue opticien préféré des français en 2017 suite à un sondage sur les offres et services des opticiens en France.<br>
Fidèle à ses valeurs, Optical Center se devait d'être présente en Russie pour apporter son soutien à l'équipe de France et l'aider à rayonner aux yeux des autres pays.<br>
L'équipe d'Optical Center ne s'est pas contentée de s’asseoir dans les gradins de cette finale et de voir le match.</p>

<br>
