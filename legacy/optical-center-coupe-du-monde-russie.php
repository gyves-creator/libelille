<p>
Dès le début de l'après-midi, l'équipe d'Optical Center présente sur les lieux s'est chargée d'insuffler une atmosphère électrique à la hauteur de l’événement en arpentant les rues moscovites et en faisant la fête sur la célèbre Place Rouge.<br>
Tout au long du match planait dans les tribunes le drapeau d'Optical Center brandi par tous les membres de la société ayant fait le déplacement.<br>
Vibrant à chaque action et but de l'équipe de France, les représentants d'Optical Center ont su représenter dignement les millions de supporters français n'ayant pas pu faire le déplacement en Russie.</p>
<p>
Hormis l'enjeu sportif, le déplacement de la société Optical Center en Russie symbolise l'attachement de la marque à son pays et aux français.</p>
