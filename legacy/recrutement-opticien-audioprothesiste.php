<h2>Optical Center : Une enseigne d'optique et d'audition leader en France</h2>

<p>
Au fil des années, Optical Center a su s'imposer comme un leader incontestable en optique et audition dans ces marchés ultra-concurrentiels.<br>
Avec plus 600 magasins répartis dans différents pays, Optical Center a réussi le pari audacieux de proposer le meilleur de l'optique et de l'audition aux meilleurs prix du marché.<br>
L'enseigne dispose également d'une clinique de chirurgie réfractrive à Lyon dotée d'équipements haut de gamme afin de répondre au mieux aux besoins des clients.</p>
<p>
La satisfaction du client est au cœur des processus mis en place par Optical Center, ce qui explique son succès et son titre d'opticien préféré des Français.<br>
Sous l'impulsion de son PDG, Optical Center a pour ambition de devenir l'enseigne n°1 en optique et audition.<br>
Pour atteindre rapidement cet objectif, Optical Center lance une grande campagne de recrutement de 700 opticiens et audioprothésistes dans toute la France.</p>
<br>

<h2>Pourquoi postuler chez Optical Center ?</h2>

<p>
Alors que le marché de l'optique s’essouffle au fil des années, Optical Center continue de se développer et connaît une croissance à 2 chiffres.</p>
<p>
Selon un sondage récent effectué en interne, les salariés de l'enseigne affirment être heureux de travailler au quotidien et être reconnus à leur juste valeur.</p>
<p>
L'enseigne propose notamment à ses employés :
</p>

<ul>
<li>Une hausse de salaire chaque année</li>
<li>Des primes importantes</li>
<li>Des formations afin de rester à la pointe du métier</li>
<li>Un poste à 30 minutes maximum de son domicile</li>
</ul>
<br>

<h2>Comment postuler chez Optical Center ?</h2>

<p>
Pour les opticiens et audioprothésistes qui souhaitent rejoindre l'aventure Optical Center, il suffit de contacter le directeur  RH de l'enseigne M. Olivier Baroukh.<br>
Pour cela, vous pouvez contacter M.Baroukh par téléphone au <u>06 11 79 50 21</u> ou par email à <u>olivier.baroukh@optical-center.com</u>.<br>
Il est également possible de déposer votre demande sur le site de Optical Center.</p>
