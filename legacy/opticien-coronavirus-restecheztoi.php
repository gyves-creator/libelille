<h2>Livraison de lunettes à domicile pour les clients de Optical Center</h2>

<p>
La France s'unit afin d’endiguer le coronavirus en se confinant chacun chez soi pour minimiser sa propagation.<br>
Situation sans précédent sous la cinquième République, tous les commerces non alimentaires sont fermés jusqu'à nouvel ordre.<br>
Ainsi, tous les magasins d'optique ont à leur tour suivi les consignes sanitaires gouvernementales en baissant leur rideau.<br>
Cependant, le leader de l'optique Optical Center désire continuer à pourvoir les Français dans leurs besoins en optique quotidiens.</p>
<p>
Ainsi, le géant français de l'optique et de l'audition lance sa campagne #ResteChezToi en fournissant ses services directement au domicile des clients.<br>
Via le site internet <u>optical-center.fr</u>, toute personne peut passer sa commande de lunettes de vue, lunettes de soleil et lentilles de contact et se voir livrer sa commande directement chez lui.<br>
Soucieux de la satisfaction de ses clients depuis son lancement en 1991, Optical Center permet ainsi à sa fidèle clientèle de bénéficier du meilleur de l'optique sans sortir de chez soi.</p>
<br>

<h2>Quelques rappels sur l'enseigne Optical Center</h2>

<p>
Avec plus de 600 magasins d'optique et d'audition, Optical Center est un leader incontesté en Europe dans son secteur d'activité.<br>
Sous l'impulsion de son PDG et fondateur Laurent Levy, Optical Center a su s'adapter aux besoins de chaque client sans exception en proposant une gamme complète de lunettes, lentilles de contact et d'appareils auditifs aux prix les plus bas du marché.</p>
<p>
En alliant professionnalisme et éthique, Optical Center a été récemment élu opticien préféré des Français pour ses services et produits.<br>
Optical Center est également connu pour avoir fondé le «temple de la vision» qui permet quotidiennement à de nombreuses familles de bénéficier de lunettes à un prix dérisoire.</p>

