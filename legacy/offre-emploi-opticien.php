<h2>Le métier d'opticien</h2>

<p>
Les statistiques montrent que le métier d'opticien continue à séduire les étudiants au vu du nombre de jeunes suivant cette voie professionnelle.</br>
Le succès des métiers liés à l'optique est si important que l'on considère qu'il y aurait en France 30% d'opticiens en trop.</br>
De ce fait, de nombreux diplômés ne trouvent pas un emploi à la sortie de leurs études à cause d'une concurrence trop élevée.</p>
<p>
Certains sont alors dans l'obligation d'ouvrir leur propre boutique d'optique afin d’exercer leur profession malgré les risques que cela comporte notamment pour un jeune diplômé.</br>
Cependant, beaucoup de jeunes n'ont pas les moyens de devenir leur propre patron et sont dans l'obligation de trouver un emploi auprès d'une enseigne d'optique.</br>
Parmi les principales marques d'optique, Optical Center est l'un des principaux recruteurs du marché.</p>
