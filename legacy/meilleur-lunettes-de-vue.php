<h2>Le marché de l'optique saturé</h2>

<p>
Tout le monde s'accorde à dire que le marché de l'optique est totalement saturé à cause du succès du métier d'opticien.</br>
Ce métier est connu pour être bien plus accessible que d'autres métier et il permet de percevoir une  rémunération supérieur à la moyenne par la suite.</br>
De ce fait, chaque années, de très nombreux étudiants obtiennent le diplôme d'opticien et beaucoup d'entre eux ouvre leur propre commerce.</br>
De ce fait, il y a aurait environ 38% d'opticien en trop en France ce qui rend le marché totalement saturé.</br>
Avec l'essor d'internet, de nombreux opticiens ont lancé leur site internet de vente de lunettes de vue, lunettes de soleil et de lentilles de contact.</p>
<p>
En seulement quelques clics ces professionnels offre la possibilité aux internautes de scanner leur ordonnance et de choisir leur paire de lunettes de vue en ligne.</br>
En quelques jours seulement, les acheteurs reçoivent leurs paires de lunettes de vue ou autre achat directement à leur domicile.</br>
Certains opticiens permettent même d'essayer les lunettes de vue en ligne afin que les internautes peuvent déterminer si la paire est adaptée à leur visage.</p>
</br>

<h2>Le marché des lunettes de vue dominé par Optical Center en 2017</h2>

<p>
Face à la concurrence féroce du marché des lunettes de vue et de soleil, Optical Center est la marque préféré des français.</br>
Cette marque a été lancé il y a environ 25 ans et compte aujourd'hui plus de 500 magasins en France mais aussi dans d'autres pays.</p>
</br>

