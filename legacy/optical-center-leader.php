<h2>L'optique : Un secteur porteur mais saturé</h2>

<p>
75% des Français présentent des problèmes de vue et, selon les estimations, 45 millions de Français en moyenne portent des lunettes de vue ou des lentilles.<br>
Il a été également démontré que les Français changent leur paire de lunettes en moyenne tous les 2 ans.<br>
Le marché de l'optique devrait dépasser 7 milliards d'euros de chiffre d'affaires en 2018, ce qui explique l'attirance pour ce secteur d'activité.<br>
Les économistes parlent de marché saturé et il y aurait plus de 30% d'opticiens en trop.<br>
L'essor d'internet n'a fait qu'amplifier cette concurrence accrue avec la naissance d'opticiens "pure player", c'est-à-dire dont l'activité s'effectue uniquement en ligne et non pas dans une boutique traditionnelle.</p>
<p>
Dans la mesure où ces magasins disposent de charges inférieures à la moyenne, ils peuvent se permettre de proposer des lunettes de vue à des prix attractifs.<br>
Face à cette forte concurrence, il est difficile de se démarquer et d'occuper une place de leader du secteur.<br>
Malgré cette concurrence, l'enseigne Optical Center a réussi ce pari de devenir un leader incontesté de l'optique avec un taux de satisfaction client très élevé.</p>
<br>


<h2>Comment s'explique le succès d'Optical Center ?</h2>

<p>
Pour se hisser dans le top 3 de l'optique en France, Optical Center a su bien cerner les besoins des clients mais dispose également de stratégies de développement qui lui sont propres.</p>
<br>

<h3>Une gamme complète de produits au meilleur prix</h3>

<p>
Pour répondre à l'ensemble des demandes des clients, il faut proposer un grand choix de produits divers et variés.<br>
Conscient de cet enjeu, Optical Center propose une gamme complète de lunettes de vue, lentilles de contact et lunettes de soleil.</p>
<p>
L'enseigne commercialise toutes les plus grandes marques de l'optique mais elle a développé également sa propre gamme de lunettes connaissant un succès important auprès des clients.<br>
Toutes les lunettes commercialisées par Optical Center sont vendues aux meilleurs prix du marché afin de satisfaire l'ensemble des clients notamment ceux dont le restant à charge est important.</p>
<br>

<h3>Le meilleur de l'optique en ligne</h3>

<p>
Le développement d'internet a créé de nouveaux modes de consommation et il est important pour les marques de s'adapter à cette évolution liée aux nouvelles technologies.<br>
Pour répondre à ces nouvelles attentes des clients, Optical Center a développé un site e-commerce ainsi qu'une application proposant tous les produits de la marque.</p>
<p>
Commander une paire de lunettes de vue en ligne sur le site de Optical Center est très facile et accessible à tous.<br>
Pour les clients souhaitant être assisté par un opticien de la même manière qu'en magasin, Optical Center a mis en ligne un système de chat en direct permettant à chaque internaute de prendre conseil auprès d'un opticien agréé.</p>
<br>

<h3>Un accès à la franchise restreint</h3>

<p>
Alors que de nombreuses marques d'optique sont en recherche permanente de nouveaux candidats à la franchise, Optical Center a mis en place une stratégie originale dans le but de servir au mieux les clients.<br>
En effet, Optical Center a fait le choix de réserver l'accès à la franchise aux personnes travaillant déjà pour l'enseigne.</p>
<p>
Les franchisés sont donc des personnes connaissant déjà bien les produits, les services et l'éthique de l'enseigne leur permettant ainsi de gérer un magasin dans les meilleures conditions et de répondre au mieux aux besoins des clients.</p>


